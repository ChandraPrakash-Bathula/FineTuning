/**
 * Every number in this application is one of three things, and the reader is
 * always told which:
 *
 *   measured    read from a Phase 1 experiment artifact
 *   calculated  derived from the model's own config.json, shown as arithmetic
 *   estimated   measured input times an assumption stated in lib/cost.ts
 *   recorded    a stored model output, as opposed to live inference
 *   live        produced by the inference backend just now
 */
export type Source = "measured" | "calculated" | "estimated" | "recorded" | "live";

const COPY: Record<Source, { label: string; title: string }> = {
  measured: { label: "measured", title: "Read from a Phase 1 experiment artifact" },
  calculated: { label: "calculated", title: "Derived from the model's config.json" },
  estimated: { label: "estimated", title: "Measured value times a configured assumption" },
  recorded: { label: "recorded", title: "A stored model output from the probe run" },
  live: { label: "live", title: "Generated by the inference backend just now" },
};

export default function Provenance({ source, className = "" }: {
  source: Source;
  className?: string;
}) {
  const c = COPY[source];
  return (
    <span className={`prov prov-${source} ${className}`} title={c.title}>
      {c.label}
    </span>
  );
}
